// TestGenerateBeforePackageCompiles covers the chicken-and-egg case: the call
// sites are written first, so the package does not type-check until the
// generator has run.
func TestGenerateBeforePackageCompiles(t *testing.T) {
	got, err := arrgen.Generate(arrgen.Config{Dir: "testdata/pregen", Types: []string{"Sample"}})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if !bytes.Contains(got, []byte("func SampleRecordBatch(")) {
		t.Error("generated output does not declare SampleRecordBatch")
	}
}

// TestGenerateReportsLoadErrors checks that a type which cannot be resolved
// reports the package's own compile errors as the likely cause.
func TestGenerateReportsLoadErrors(t *testing.T) {
	_, err := arrgen.Generate(arrgen.Config{Dir: "testdata/pregen", Types: []string{"Absent"}})
	if err == nil {
		t.Fatal("Generate succeeded, want an error")
	}
	if !strings.Contains(err.Error(), "does not type-check") {
		t.Errorf("error = %q, want it to surface the package's compile errors", err)
	}
}

func TestGenerateNoTypes(t *testing.T) {
	if _, err := arrgen.Generate(arrgen.Config{Dir: "testdata/basic"}); err == nil {
		t.Error("Generate with no types succeeded, want an error")
	}
}

func TestGenerateMissingPackage(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "empty")
	if err := os.Mkdir(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if _, err := arrgen.Generate(arrgen.Config{Dir: dir, Types: []string{"Metric"}}); err == nil {
		t.Error("Generate in a directory with no Go files succeeded, want an error")
	}
}

func first(b []byte, n int) []byte {
	if len(b) < n {
		return b
	}
	return b[:n]
}
