// gearhash_gen writes gearhash_table.go. Entry [seed][n] is the first 8 bytes
// of md5(seed*64 ++ n*64) read big-endian, matching the hex prefix produced by
// the C++ generate_hash helper.
package main

import (
	"bytes"
	"crypto/md5"
	"encoding/binary"
	"fmt"
	"go/format"
	"log"
	"os"
)

const numGearTables = 8

func main() {
	var out bytes.Buffer
	out.WriteString(header)
	out.WriteString("package cdc\n\n")
	out.WriteString("// gearTables holds the gear hash tables used by the rolling hash.\n")
	fmt.Fprintf(&out, "var gearTables = [%d][256]uint64{\n", numGearTables)
	var buf [128]byte
	for seed := range numGearTables {
		out.WriteString("\t{\n")
		for n := range 256 {
			for i := range buf {
				if i < 64 {
					buf[i] = byte(seed)
				} else {
					buf[i] = byte(n)
				}
			}
			sum := md5.Sum(buf[:])
			fmt.Fprintf(&out, "\t\t0x%016x,\n", binary.BigEndian.Uint64(sum[:8]))
		}
		out.WriteString("\t},\n")
	}
	out.WriteString("}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("gearhash_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

